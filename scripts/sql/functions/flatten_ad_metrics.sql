-- level='ad' and upserts typed rows into silver_ad_metrics.
--
-- Companion to scripts/sql/silver_ad_metrics.sql -- column list here MUST stay in
-- sync with that DDL (both generated from the same field lists; see
-- /private/tmp/.../gen_silver_flatten_fns.py and gen_silver_ddl.py in this
-- session's scratchpad if regenerating).
--
-- Confirmed live (app/services/meta/insights.py _build_row): each Bronze
-- row is tagged with its own level at parent_ids->>'level', NOT
-- request_params (request_params->'levels' is the whole batch's requested
-- levels, plural, not this row's level) -- so the WHERE clause filters on
-- parent_ids, not request_params.
--
-- Dedup: Bronze is append-only and not deduplicated at write time, so this
-- picks the most-recently-ingested row per (ad_id, date_start,
-- date_stop) via DISTINCT ON, same pattern as
-- scripts/sql/functions/compute_base_ad_metrics.sql. Every NUMERIC/DATE
-- cast is NULLIF-guarded against empty strings so one malformed field
-- doesn't fail the whole batch.
--
-- Run this ONCE in the Supabase SQL Editor -- PostgREST can't execute DDL.
-- Call from Python via RPC: POST {supabase_url}/rest/v1/rpc/flatten_ad_metrics


