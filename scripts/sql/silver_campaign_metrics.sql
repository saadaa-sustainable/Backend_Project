-- Silver layer: silver_campaign_metrics -- one row per campaign per reporting
-- date range, flattened from raw_dump_meta (object_type='insights',
-- level='campaign') JSONB payloads into typed columns.
--
-- Full-flatten design (confirmed with the user 2026-08-04): every field in
-- app/core/meta_registry.py's INSIGHTS_FIELD_GROUPS gets its own column
-- here, so Silver holds ALL fetchable data. Gold layer is where a LIMITED,
-- curated subset gets selected for the actual dashboard -- this table is
-- deliberately not that.
--
-- Column typing:
--   * identity columns: TEXT / TIMESTAMPTZ, present (nullable) on all 4
--     level tables regardless of whether Meta returns them at this level --
--     app/core/meta_registry.py's LEVEL_RESTRICTED_METRICS confirms only 6
--     *metric* fields are level-gated, not identity fields.
--   * 23 core metrics (delivery/spend/clicks/rate_and_cost) are
--     NUMERIC -- confident, well-established plain-scalar Meta fields.
--   * 135 remaining metrics are JSONB, one column per registry field
--     name. Some of these are genuinely array/object-shaped in Meta's API
--     (nested action_type breakdowns, e.g. `actions`, `purchase_roas`);
--     others are simply NOT YET LIVE-VERIFIED as scalar. JSONB is the safe,
--     lossless default either way -- reclassify to NUMERIC once a real
--     captured payload confirms a given field's actual shape, matching the
--     project's standing rule of live-verifying rather than guessing.
--
-- Run this ONCE in the Supabase SQL Editor -- PostgREST can't execute DDL.


